  GROUP BY
    c.CIK, c.ENTITY_ID, COALESCE(c.DISPLAY_NAME, c.ENTITY_NAME),
    c.ENTITY_TYPE, c.SIC, c.SIC_DESCRIPTION,
    c.STATE_OF_INCORPORATION, c.FISCAL_YEAR_END
),
active_graph_subject AS (
  SELECT n.NODEID
  FROM {{ database }}.NEO4J_GRAPH_MIGRATION.MDM_GRAPH_NODES n
  JOIN {{ database }}.NEO4J_GRAPH_MIGRATION.GRAPH_ACTIVE_POINTER ptr
    ON ptr.POINTER_ID = 'active'
   AND ptr.ACTIVE_GENERATION_ID = n.GENERATION_ID
  WHERE n.ENTITY_TYPE = 'company'
