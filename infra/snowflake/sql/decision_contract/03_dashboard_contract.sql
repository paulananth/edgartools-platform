  f.INTERIM_FISCAL_PERIOD, f.INTERIM_ACCESSION_NUMBER, f.INTERIM_REVENUE,
  f.INTERIM_NET_INCOME, f.INTERIM_FEATURES_COVERAGE,
  s.READINESS_STATE, s.NOT_READY_REASON, s.DECISION_CONTRACT_VERSION,
  s.DECISION_WATERMARK, s.BUSINESS_DATE, s.GOLD_UPDATED_AT,
  s.GRAPH_GENERATION_ID, s.GRAPH_ACTIVATED_AT, s.COVERAGE_STATE,
  s.ALIGNMENT_STATUS
FROM tracked t
JOIN active_graph_subject g ON g.NODEID = t.ENTITY_ID
JOIN {{ database }}.EDGARTOOLS_DECISION.SUBJECT_FEATURE_SCREEN f
  ON f.CIK = t.CIK
CROSS JOIN display_status s;

