  t.SIC_DESCRIPTION, t.STATE_OF_INCORPORATION, t.FISCAL_YEAR_END,
  f.FY_PERIOD_END, f.FY_FISCAL_YEAR, f.FY_ACCESSION_NUMBER, f.FY_REVENUE,
  f.FY_NET_INCOME, f.FY_TOTAL_ASSETS, f.FY_TOTAL_EQUITY, f.FY_FREE_CASH_FLOW,
