    'derived_sample' AS probe,
    CIK,
    ACCESSION_NUMBER,
    FISCAL_YEAR,
    FISCAL_PERIOD,
    PERIOD_END,
    EBITDA,
    EPS_DILUTED,
    EBITDA_MARGIN,
