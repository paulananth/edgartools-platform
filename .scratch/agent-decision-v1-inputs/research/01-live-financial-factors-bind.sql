-- 1. Full column lists.
SELECT 'factors_cols' AS probe, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM EDGARTOOLS_PROD.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_CATALOG = 'EDGARTOOLS_PROD'
  AND TABLE_SCHEMA = 'EDGARTOOLS_GOLD'
  AND TABLE_NAME = 'FINANCIAL_FACTORS'
ORDER BY ORDINAL_POSITION;

SELECT 'derived_cols' AS probe, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM EDGARTOOLS_PROD.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_CATALOG = 'EDGARTOOLS_PROD'
  AND TABLE_SCHEMA = 'EDGARTOOLS_GOLD'
  AND TABLE_NAME = 'FINANCIAL_DERIVED'
ORDER BY ORDINAL_POSITION;

SELECT 'silver_derived_cols' AS probe, ORDINAL_POSITION, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM EDGARTOOLS_PROD.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_CATALOG = 'EDGARTOOLS_PROD'
  AND TABLE_SCHEMA = 'EDGARTOOLS_SILVER'
  AND TABLE_NAME = 'SEC_FINANCIAL_DERIVED'
ORDER BY ORDINAL_POSITION;

-- Named bind-gap columns (factors / derived / silver).
SELECT 'named_bind_cols' AS probe, TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME
FROM EDGARTOOLS_PROD.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_CATALOG = 'EDGARTOOLS_PROD'
  AND (
        (TABLE_SCHEMA = 'EDGARTOOLS_GOLD' AND TABLE_NAME IN ('FINANCIAL_FACTORS', 'FINANCIAL_DERIVED'))
     OR (TABLE_SCHEMA = 'EDGARTOOLS_SILVER' AND TABLE_NAME = 'SEC_FINANCIAL_DERIVED')
  )
  AND COLUMN_NAME IN (
        'EBITDA', 'EPS_DILUTED', 'EBITDA_MARGIN',
        'RETURN_ON_EQUITY', 'RETURN_ON_ASSETS',
        'ROE', 'ROA', 'ROIC',
        'OPERATING_MARGIN',
        'REVENUE', 'GROSS_PROFIT', 'EBIT', 'NET_INCOME',
        'TOTAL_ASSETS', 'TOTAL_LIABILITIES', 'TOTAL_EQUITY',
        'CASH_AND_EQUIVALENTS', 'TOTAL_DEBT',
        'OPERATING_CASH_FLOW', 'FREE_CASH_FLOW',
        'GROSS_MARGIN', 'NET_MARGIN'
  )
ORDER BY TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME;

-- 2. Row counts, distinct CIK, FY mix on FINANCIAL_FACTORS.
SELECT
    'factors_counts' AS probe,
    COUNT(*) AS row_count,
    COUNT(DISTINCT CIK) AS distinct_cik,
    COUNT_IF(UPPER(FISCAL_PERIOD) = 'FY') AS fy_rows,
    COUNT_IF(UPPER(FISCAL_PERIOD) <> 'FY') AS non_fy_rows,
    COUNT(DISTINCT IFF(UPPER(FISCAL_PERIOD) = 'FY', CIK, NULL)) AS fy_ciks,
    COUNT(DISTINCT IFF(UPPER(FISCAL_PERIOD) <> 'FY', CIK, NULL)) AS non_fy_ciks
FROM EDGARTOOLS_PROD.EDGARTOOLS_GOLD.FINANCIAL_FACTORS;

SELECT
    'factors_period_mix' AS probe,
    FISCAL_PERIOD,
    COUNT(*) AS row_count,
    COUNT(DISTINCT CIK) AS distinct_cik
FROM EDGARTOOLS_PROD.EDGARTOOLS_GOLD.FINANCIAL_FACTORS
GROUP BY FISCAL_PERIOD
ORDER BY row_count DESC;

SELECT
    'derived_counts' AS probe,
    COUNT(*) AS row_count,
    COUNT(DISTINCT CIK) AS distinct_cik,
    COUNT_IF(UPPER(FISCAL_PERIOD) = 'FY') AS fy_rows,
    COUNT_IF(UPPER(FISCAL_PERIOD) <> 'FY') AS non_fy_rows
FROM EDGARTOOLS_PROD.EDGARTOOLS_GOLD.FINANCIAL_DERIVED;

SELECT
    'silver_derived_counts' AS probe,
    COUNT(*) AS row_count,
    COUNT(DISTINCT CIK) AS distinct_cik
FROM EDGARTOOLS_PROD.EDGARTOOLS_SILVER.SEC_FINANCIAL_DERIVED;

