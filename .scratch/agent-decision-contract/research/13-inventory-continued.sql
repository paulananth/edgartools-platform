SELECT 'decision_objects' AS probe, TABLE_NAME AS k1
FROM EDGARTOOLS_PROD.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'EDGARTOOLS_DECISION'
ORDER BY 1;

