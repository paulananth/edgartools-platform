SELECT 'gold_company' AS probe, COUNT(*)::VARCHAR AS n1 FROM EDGARTOOLS_PROD.EDGARTOOLS_GOLD.COMPANY;
SELECT 'mdm_company_entity' AS probe, COUNT(*)::VARCHAR AS n1 FROM EDGARTOOLS_PROD.EDGARTOOLS_GOLD.MDM_COMPANY_ENTITY;
SELECT 'mdm_company_entity_active' AS probe, COUNT(*)::VARCHAR AS n1
FROM EDGARTOOLS_PROD.EDGARTOOLS_GOLD.MDM_COMPANY_ENTITY
